<?php

namespace Pterodactyl\Http\Controllers\Api\Client\Servers;

use Illuminate\Http\Request;
use Illuminate\Http\JsonResponse;
use Pterodactyl\Models\Server;
use Pterodactyl\Facades\Activity;
use Pterodactyl\Repositories\Wings\DaemonFileRepository;
use Pterodactyl\Http\Controllers\Api\Client\ClientApiController;

class MinecraftConfigController extends ClientApiController
{
    public function __construct(private DaemonFileRepository $fileRepository)
    {
        parent::__construct();
    }

    /**
     * Get parsed server.properties.
     */
    public function index(Request $request, Server $server): JsonResponse
    {
        try {
            $raw = $this->fileRepository->setServer($server)->getContent('server.properties');
        } catch (\Throwable $e) {
            return response()->json(['properties' => []]);
        }

        $properties = [];
        $lines = explode("\n", str_replace("\r", '', $raw));

        foreach ($lines as $line) {
            $line = trim($line);
            if (empty($line) || str_starts_with($line, '#') || str_starts_with($line, '!')) {
                continue;
            }

            $pos = strpos($line, '=');
            if ($pos === false) {
                continue;
            }

            $key = trim(substr($line, 0, $pos));
            $val = trim(substr($line, $pos + 1));

            // Convert types
            if ($val === 'true') {
                $properties[$key] = true;
            } elseif ($val === 'false') {
                $properties[$key] = false;
            } elseif (is_numeric($val) && !in_array($key, ['level-seed', 'motd', 'server-ip', 'rcon.password'])) {
                $properties[$key] = str_contains($val, '.') ? (float) $val : (int) $val;
            } else {
                $properties[$key] = $val;
            }
        }

        return response()->json(['properties' => $properties]);
    }

    /**
     * Update server.properties.
     */
    public function update(Request $request, Server $server): JsonResponse
    {
        $newProps = $request->input('properties', []);
        if (!is_array($newProps)) {
            return response()->json(['error' => 'Format de propriétés invalide.'], 422);
        }

        // Try reading existing content to preserve layout/comments if possible
        try {
            $raw = $this->fileRepository->setServer($server)->getContent('server.properties');
            $lines = explode("\n", str_replace("\r", '', $raw));
        } catch (\Throwable $e) {
            $lines = [
                '# Minecraft server properties - Generated by NXSLab Cloud',
                '# ' . date('c'),
            ];
        }

        $handledKeys = [];
        $outputLines = [];

        foreach ($lines as $line) {
            $trimmed = trim($line);
            if (empty($trimmed) || str_starts_with($trimmed, '#') || str_starts_with($trimmed, '!')) {
                $outputLines[] = $line;
                continue;
            }

            $pos = strpos($line, '=');
            if ($pos === false) {
                $outputLines[] = $line;
                continue;
            }

            $key = trim(substr($line, 0, $pos));
            if (array_key_exists($key, $newProps)) {
                $val = $this->formatPropertyValue($newProps[$key]);
                $outputLines[] = "{$key}={$val}";
                $handledKeys[] = $key;
            } else {
                $outputLines[] = $line;
            }
        }

        // Append any new properties that were not in the file originally
        foreach ($newProps as $key => $val) {
            if (!in_array($key, $handledKeys)) {
                $val = $this->formatPropertyValue($val);
                $outputLines[] = "{$key}={$val}";
            }
        }

        $finalContent = implode("\n", $outputLines) . "\n";
        $this->fileRepository->setServer($server)->putContent('server.properties', $finalContent);

        Activity::event('server:minecraft.config-updated')
            ->subject($server)
            ->property(['keys' => array_keys($newProps)])
            ->log('mise à jour des propriétés du serveur Minecraft');

        return response()->json(['success' => true, 'properties' => $newProps]);
    }

    private function formatPropertyValue(mixed $val): string
    {
        if (is_bool($val)) {
            return $val ? 'true' : 'false';
        }
        if (is_null($val)) {
            return '';
        }
        return (string) $val;
    }
}
